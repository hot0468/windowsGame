/** 지금 예고 중인 청구. 화면이 날짜 계산을 다시 하지 않게 한다. */
export function noticedBills(day: number): Bill[] {
  return BILLS.filter((b) => b.day - NOTICE_DAYS <= day && day <= b.day)
}
