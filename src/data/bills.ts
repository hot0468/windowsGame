/**
 * 목돈 청구 — **미리 알려 주고, 며칠 뒤에 빠져나간다.**
 *
 * ## 왜 만들었나
 * 이 게임에서 **은행 대출을 굳이 안 써도 판이 돌아갔다**(2026-08-09 설계자 지시). 나가는
 * 돈이 전부 잘게 쪼개져 있어서다 — 생활비는 매일, 구독은 만 원, 활동비는 확인창이 미리
 * 적는다. 그래서 대출도 중고마켓도 정기예금 만기도 서로 얽힐 일이 없었다.
 * **한 번에 큰돈이 나가는 날**이 그 셋에 처음으로 쓸모를 준다.
 *
 * ## ⚠️ 무작위가 아니다 — 날짜가 정한다
 * 어느 날 얼마가 나가는지는 표에 적혀 있고 예고도 표가 정한다. 주사위를 굴리면 "왜
 * 하필 지금"에 답할 수 없고, 이 게임의 판정에 무작위가 없다는 규칙과 어긋난다
 * (장비 고장·정규직 합격·공모전 심사와 같은 자리).
 *
 * ## ⚠️ 못 내면 파산이 아니라 평판이다
 * 잔액이 모자랄 때 그냥 빼면 소지금이 음수가 되어, **단발 사건이 파산을 직접 만든다** —
 * 이 게임은 물가로 끝나기로 돼 있어 종결 사유가 흐려진다. 대신 **가진 만큼만 내고 모자란
 * 몫은 평판으로 치른다**(그몽 마감 미스와 같은 판형: 돈이 아니라 평판으로 받는다).
 *
 * ## ⚠️ 수입이 아니라 지출이다 — `nightPayoutPending`에 넣지 않는다
 * 그 술어는 "받을 돈이 남았으니 죽음 판정을 미룬다"는 뜻이다(구독료와 같은 이유).
 */

/** 청구 하나. */
export interface Bill {
  id: string
  /** 아웃룩 발신자. ⚠️ 실존 상호 금지(알바몬·그몽과 같은 규칙). */
  from: string
  subject: string
  /** 예고 메일 본문. **얼마가 언제 나가는지 반드시 적는다**(숨은 비용 금지). */
  text: string
  /** 이 날 밤에 빠져나간다. */
  day: number
  amount: number
}

