/**
 * 상금 등급 하나.
 *
 * `odds`는 **분모**다(`1/odds` 확률). 정수 분모로 두는 것이 "20장에 한 번"처럼
 * 화면에 그대로 적히기 때문이다 — 확률을 숨기지 않는 것이 이 게임의 규칙이다.
 */
export interface LotteryPrize {
  /** 등수 라벨(화면·당첨 문구 공용). */
  label: string
  /** 당첨 확률의 분모. 1/odds 확률로 당첨된다. */
  odds: number
  /** 상금. */
  amount: number
}

/**
 * 상금표. **위에서부터 확률이 높아지고 상금이 작아진다.**
 *
 * ⚠️ **판정은 이 배열 순서를 따른다**(`systems/lottery.ts`) — 위쪽(희귀·고액)부터
 * 물어보므로 한 장이 두 등급에 동시에 당첨되지 않는다.
 *
 * ## 기대값 계산 (표 값 10,000원)
 *  - 1등  1/1,000,000 × 500,000,000 =  500.0
 *  - 2등     1/50,000 ×   5,000,000 =  100.0
 *  - 3등      1/2,000 ×     200,000 =  100.0
 *  - 4등        1/200 ×      50,000 =  250.0
 *  - 5등         1/25 ×      20,000 =  800.0
 *  - 6등         1/10 ×      10,000 = 1000.0  (본전 — 표 값을 돌려받는다)
 *  합계 **2,750원** = 표 값의 **27.5%**. 실제 로또의 환급률(약 50%)보다도 훨씬 박하다.
 *
 * **72.5%를 잃는다**는 것이 이 장치의 성격 전부다: 복권은 며칠을 사 주지 않는다.
 * 사 주는 것은 **"오늘 밤 뭔가 일어날지도 모른다"는 감각**뿐이고, 그 대가로 죽는 날이
 * 아주 조금씩 앞당겨진다. 은행 대출과 같은 방향의 장치이고, 그래서 둘 다
 * `balance.verify.test.ts`가 "그래도 판은 끝난다"를 시뮬레이션으로 지킨다.
 *
 * ⚠️ **6등(본전)이 1/10인 것이 "아무것도 안 일어나는 복권"을 막는 지점이다.**
 * 열 장에 한 장은 표 값이 돌아오므로 손실이 체감상 완만해진다. 그럼에도 총 환급률은
 * 27.5%라 실제로는 계속 잃는다 — 이 어긋남이 복권이라는 물건의 정체다.
 */
