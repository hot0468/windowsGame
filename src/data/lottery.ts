/**
 * 복권 — **표마다 따로 굴리고, 결과는 주 1회 추첨일에 열린다.**
 *
 * ## 설계자 지시
 * "복권도 넣어. 당첨확률 엄청 낮게" / "복권은 살때마다 확률이 새로 나온다니까"
 * → **한 장 한 장이 독립 시행이다.** 오늘 산 표가 내일 다시 굴러가지도 않고,
 * 새로 고침해도 이미 산 표의 결과가 바뀌지 않는다(아래 "결정성" 참조).
 *
 * "복권은 로또처럼 일주일에 한 번 추첨해"(2026-08-17)
 * → 산 표는 **다음 토요일 밤**까지 미추첨으로 기다린다. ⚠️ **독립 시행과 어긋나지 않는다** —
 * 바뀐 것은 굴림이 아니라 **결과가 열리는 시각**이고, 그 기다림이 복권의 성격 자체다:
 * 즉시 결과가 나오면 그건 복권이 아니라 긁는 것이고, 한 슬롯에 몇 번이고 반복해
 * 분산을 갈아 마실 수 있게 된다(1회 상한이 막던 것이 사라진다).
 *
 * ## ⚠️ 기대값은 반드시 음수다
 * 표가 자기 값을 하면 복권은 **수입원**이 되고, 그 순간 이 게임의 핵심 보증
 * ("생활비가 결국 이긴다 = 판은 반드시 끝난다")이 죽는다. 그래서 상금표의 기대값이
 * 표 값보다 **낮다는 것을 테스트가 데이터에서 직접 계산해 지킨다**(`lottery.test.ts`) —
 * 나중에 누가 상금을 올리다가 조용히 뒤집는 것을 막기 위해서다.
 * (은행의 `LOAN_RATE > DEPOSIT_RATE` 부등식과 정확히 같은 장치다.)
 *
 * ## ⚠️ 아무것도 안 터지는 복권은 그냥 돈 지우는 버튼이다
 * "엄청 낮게"는 **1등**에만 적용된다. 아래 등수를 함께 두어 몇 장에 한 번은 무언가가
 * 일어나게 한다 — 그 감각이 없으면 두 번째 장을 살 이유가 없고, 장치가 아니라
 * 잘못 만든 버튼이 된다.
 *
 * ## 결정성 (`Math.random` 금지)
 * 굴림은 `systems/lottery.ts`의 시드 PRNG가 한다. 시드에 **구매 일련번호**가 들어가므로
 * 장마다 새로 굴러가고, 그 일련번호가 세이브에 남으므로 **새로 고침해도 이미 산 표는
 * 다시 굴러가지 않는다.** 재굴림이 되면 새로 고침이 최적 전략(세이브 스커밍)이 된다.
 */

