/**
 * 강제 회복 기간 — 자원이 바닥나 며칠간 주저앉는 사건.
 *
 * ## ⚠️ 게임을 끝내지 않는다
 * 2026-08-14 육성물 전환(설계자 지시: "카이로소프트처럼 완전한 게임오버는 없었으면").
 * 예전에는 소지금 0 = 파산, 멘탈 0 = 번아웃으로 **판이 강제 종료**됐고, 물가 곡선이
 * 그 종료를 반드시 오게 만드는 장치였다. 지금은 둘 다 **며칠을 뺏는 사건**이다.
 *
 * ## 왜 시간을 뺏는가
 * 이 게임에서 가장 희소한 자원은 턴이다(하루 2슬롯, 활동 하나가 1턴). 돈을 뺏으면
 * 부자에게만 벌이 가볍고, 스탯을 깎으면 **쌓아 온 것이 무너져** 육성물의 전제가 흔들린다.
 * 시간은 누구에게나 똑같이 비싸고, 잃어도 **되돌릴 수 있는 것을 잃지는 않는다.**
 *
 * ## ⚠️ 빠져나오는 법이 둘인 것이 규칙이다
 * 날이 지나면 저절로 풀리고(`RECOVERY_DAYS`), 돈을 쓰면 즉시 풀린다(`RECOVERY_EXIT_FEE`).
 * `illness.ts`와 같은 규칙이다 — 하나만 두면 회복은 벌칙이거나 통행세이고,
 * **돈과 시간 중 무엇을 낼지가 선택**이라야 장치가 된다.
 *
 * ⚠️ 단, **파산은 돈으로 빠져나올 수 없다**(돈이 없어서 걸린 상태다). 그쪽의 탈출구는
 * 아래 `BANKRUPT_RELIEF_DAYS`가 정하는 구제금이고, 그래서 두 회복의 탈출 구조가 다르다.
 */

/**
 * 주저앉는 기간(일). 취침마다 하루씩 준다.
 *
 * 3일인 것은 `ILLNESS_DAYS`와 같은 값이라서가 아니라 **하루 2슬롯 × 3일 = 6턴**이
 * "한 주를 통째로 날렸다"는 체감의 최소치이기 때문이다. 그보다 짧으면 벌이 아니고,
 * 길면 플레이어가 화면을 떠난다.
 */
export const RECOVERY_DAYS = 3

/**
 * 파산으로 주저앉을 때 쥐여 주는 **생활비의 배수**.
 *
 * ⚠️ **고정 금액이면 안 된다.** 처음에는 150,000원 정액이었는데, 물가가 계속 오르는
 * 게임이라 후반에는 그 돈이 **하루치 생활비도 안 됐다**(101일차 생활비 139,586원).
 * 그러면 풀려난 그 밤에 다시 0이 되어 파산→회복→파산이 영원히 돈다 — 느리게 오는
 * 게임오버다. `balance.verify.test.ts`의 "그래도 거기서 빠져나온다"가 실제로 잡았다.
 *
 * 배수는 "다시 벌 기회"를 만들 만큼이되 넉넉하면 안 된다(파산이 이득이 되면 일부러
 * 쓰러진다). 회복 기간(`RECOVERY_DAYS`)을 나고도 며칠이 남는 정도가 그 선이다.
 */
export const BANKRUPT_RELIEF_DAYS = 6

/**
 * 번아웃으로 주저앉을 때 돌려주는 멘탈.
 *
 * ⚠️ **`BANKRUPT_RELIEF_DAYS`와 같은 이유로 0이 아니다.** 멘탈 0인 채로 풀려나면 다음 활동
 * 하나로 곧바로 다시 0이 된다. 다만 절반까지만 준다 — 번아웃이 **회복의 지름길**이
 * 되면 일부러 쓰러지는 것이 최적 전략이 된다.
 */
export const BURNOUT_RELIEF = 50

/**
 * 회복을 즉시 끝내는 비용(원). 번아웃에만 쓴다(파산은 돈이 없어서 걸린 상태다).
 *
 * ⚠️ **물가 배율을 안 탄다**(`CLINIC_FEE`와 같은 규칙) — 후반에 회복 탈출이 곧 파산이면
 * 한 번의 무리에 벌을 두 번 주는 것이다. **`BANKRUPT_RELIEF_DAYS`와 다른 판단인 것이
 * 의도다**: 구제금은 안 주면 갇히므로 물가를 따라가야 하고, 이 비용은 안 내도 며칠 뒤
 * 풀리므로 따라갈 이유가 없다.
 */
export const RECOVERY_EXIT_FEE = 120_000
