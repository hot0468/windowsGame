/**
 * 콜센터 업무 — QnA 문서와 걸려 오는 콜.
 *
 * ## 이 파일이 갖는 것과 갖지 않는 것
 * 콜은 **수치를 하나도 갖지 않는다**(알바몬 공고·배달 메뉴와 같은 규칙). 콜이 아는 것은
 * "누가 무엇을 묻는가"와 "어느 QnA가 정답인가"뿐이고, 보너스 금액은 전부 아래 `BONUS_TIERS`
 * 하나가 정한다 — 콜마다 금액을 적으면 "빨리 처리하면 더 받는다"는 규칙이 콜 수만큼 갈라진다.
 *
 * ## 왜 기본급이 아니라 보너스인가
 * 출근 활동(`commute`)은 돈을 한 푼도 만지지 않고 급여의 단일 출처는 `Career.salary`다
 * (`data/careers.ts`). 미니게임이 그 자리에서 현금을 주면 같은 급여가 두 곳에 생긴다.
 * 그래서 여기서 버는 것은 **급여일에 기본급과 함께 들어오는 보너스**(`Employment.bonus`)이고,
 * 정산은 `systems/employment.ts`의 `payWages` 한 곳을 그대로 지난다.
 *
 * ⚠️ `Math.random`·`Date` 금지 — 오늘 걸려 오는 콜은 **날짜의 함수**다(뉴스와 같은 규칙).
 *    경과 시간만은 실시간이고, 그것은 화면(컴포넌트)이 잰다.
 * ⚠️ **실존 브랜드·실존 인물 이름 금지.** 전부 지어낸 상호다.
 */

