/**
 * 아픔 — 행동력을 바닥에 붙여 두고 굴리면 앓아눕는다.
 *
 * ## ⚠️ 번아웃과 다른 축이다
 * 번아웃은 **같은 일을 반복해서** 멘탈이 깎이는 것이고(`systems/burnout.ts`), 아픔은
 * **몸을 다 쓰고도 계속 움직여서** 생긴다. 판정 근거가 하나는 활동 이력이고 하나는
 * 행동력이라 서로를 모른다 — 겹치게 만들면 한 번의 무리에 벌을 두 번 주는 것이 된다.
 * 그래서 아픔은 **게임오버를 만들지 않는다**(파산·번아웃 둘만 판을 끝낸다).
 *
 * ## ⚠️ 활동을 막지 않는다
 * 날씨와 같은 이유다(`data/weather.ts`) — `canRun`에 게이트를 만들면 스케줄러 예약과
 * 자동 진행이 조용히 스킵된다. 아픔이 하는 일은 **회복을 반으로 줄이고 효율을 깎는 것**,
 * 곧 "아픈 채로 계속 굴릴 수는 있는데 그게 남는 장사가 아니다"다.
 *
 * ## 나는 법이 둘인 것이 규칙이다
 * 날이 지나면 저절로 낫고(`ILLNESS_DAYS`), 돈을 쓰면 즉시 낫는다(`clinic` 활동).
 * 하나만 두면 아픔은 벌칙이거나 통행세다 — **돈과 시간 중 무엇을 낼지가 선택이다.**
 */

