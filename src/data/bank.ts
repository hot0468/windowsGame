/**
 * 은행 — 예금·대출 수치.
 *
 * ## 이 시스템이 있는 이유
 * 물가는 10일마다 오르고 결국 아무도 못 버틴다(설계상 자연 종결). 그런데 그 종결까지의
 * 구간이 **잘하든 못하든 똑같으면** 판을 잘 굴릴 이유가 없다. 은행은 그 구간을
 * **플레이의 결과로 늘리고 줄이는** 첫 장치다:
 *  - **예금**: 오늘 쓸 수 없게 묶는 대신 이자가 붙는다 → 계획한 만큼 며칠을 번다.
 *  - **대출**: 오늘 당장 현금이 생기는 대신 이자가 나를 향해 붙는다 → **죽는 날이 앞당겨진다.**
 *
 * ## ⚠️ 절대 깨면 안 되는 것
 * **대출 이율 > 예금 이율.** 뒤집히면 "빌려서 예금하기"가 무위험 차익이 되어 판이
 * 무한해진다. `bank.test.ts`가 **데이터에서 직접 읽어** 이 부등식을 지킨다 —
 * 이율을 손보다가 조용히 열리는 것을 막기 위해서다.
 *
 * ## 결정성
 * `Math.random`·`Date` 금지(다른 systems와 같은 규칙). 이자는 전부 정해진 일수·정해진
 * 이율의 곱이라 굴림이 없다 — 그래서 화면이 "며칠 뒤 얼마"를 거짓 없이 미리 보여 줄 수 있다.
 */

/**
 * 자유예금 **일 이율**. 언제든 빼 쓸 수 있으므로 낮다.
 *
 * 0.4%/일 ≈ 30일에 12.7%. 생활비(30,000원~)에 비하면 소소하지만,
 * "쓰지 않고 남긴 돈이 조금씩 불어난다"는 감각을 만드는 것이 이 계좌의 역할이다.
 */
export const SAVINGS_RATE = 0.004

/**
 * 정기예금 **일 이율**. 만기까지 못 빼는 대신 자유예금의 두 배가 넘는다.
 *
 * ⚠️ **이 계좌가 "계획을 보상한다"는 이 시스템의 본체다.** 자유예금만 있으면 은행은
 * "남는 돈을 넣어 두는 곳"에 그치고 플레이가 달라지지 않는다. 만기(= 못 쓰는 기간)를
 * 걸어야 비로소 "앞으로 며칠은 이 돈 없이 버틸 수 있는가"라는 판단이 생긴다.
 */
export const DEPOSIT_RATE = 0.009

/** 정기예금 만기까지의 일수. 물가 인상 주기(10일)보다 길게 잡아 한 구간을 통째로 건너게 한다. */
export const DEPOSIT_TERM_DAYS = 12

/** 정기예금 최소 가입 금액. 이보다 작으면 이자가 반올림에 먹혀 의미가 없다. */
export const DEPOSIT_MIN = 100_000

/**
 * 대출 **일 이율**. ⚠️ **반드시 예금 이율보다 높다**(위의 차익 금지 규칙).
 *
 * 1.8%/일 ≈ 30일에 71%. 무섭게 잡은 것이 의도다 — 대출은 "며칠을 사는" 도구이지
 * "돈을 버는" 도구가 아니어야 한다. 갚지 못하면 이자가 이자를 낳아 **파산이 앞당겨진다**.
 */
export const LOAN_RATE = 0.018

/**
 * 무직일 때의 대출 한도. 생활비 며칠치 정도라 "한숨 돌리는" 크기다.
 *
 * ⚠️ 0으로 두지 않는다 — 무직이 제일 급한 사람인데 그 사람만 못 빌리면 장치가
 * 아무 때도 쓰이지 않는다. 대신 작게 둬서 무직 대출로는 판을 뒤집을 수 없게 한다.
 */
export const LOAN_LIMIT_BASE = 300_000

/**
 * 재직 중일 때 한도에 더해지는 **급여 배수**.
 *
 * ⚠️ **한도를 고용에 묶은 것이 이 시스템과 정규직을 잇는 지점이다.** 취직하면
 * 급여의 2배까지 더 빌릴 수 있고(청람그룹 460만 → 한도 950만), 해고되면 한도가
 * 다시 30만으로 떨어진다 — **빚은 그대로인 채로.** 그것이 해고의 진짜 무게다.
 */
export const LOAN_LIMIT_SALARY_MULTIPLE = 2

/** 한 번에 빌리거나 갚을 수 있는 최소 금액. 1원 단위 조작을 막는다. */
export const LOAN_MIN = 50_000

/**
 * 대출 잔액이 이 배수를 넘으면 화면이 위험을 경고한다(한도 대비).
 * 판정이 아니라 표시용이다 — 규칙은 `systems/bank.ts`가 갖는다.
 */
export const LOAN_DANGER_RATIO = 0.7

/** 거래 내역을 세이브에 남기는 최대 건수. 오래된 것부터 버린다(세이브가 무한히 크면 안 된다). */
export const LEDGER_LIMIT = 40

/** 은행 이름. 화면 두 곳(사이트·거래 내역)이 같은 문자열을 봐야 한다. */
export const BANK_NAME = '네이놈은행'
