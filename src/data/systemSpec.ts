import { dateOf } from './calendar'

/**
 * 시스템 속성 창이 적는 사양 — **연출이고 규칙이 아니다.**
 *
 * ## ⚠️ 수치가 게임을 하나도 안 건드린다
 * 여기 적힌 램·저장소는 아무것도 제한하지 않는다. 실제 윈도우의 '정보' 화면을 옮겨 온
 * 것이고(`BlueScreen`·VS 코드 창과 같은 부류), 이 값이 바뀌어도 턴·돈·활동은 그대로다.
 * ⚠️ **여기에 게임 규칙을 걸지 말 것** — 사양이 활동을 막기 시작하면 플레이어가 고칠 수
 * 없는 잠금이 된다(이 게임에는 컴퓨터를 업그레이드하는 통로가 없다).
 *
 * ## ⚠️ 제조사 이름을 지어내지 않는다
 * 물건 목록(`data/items.ts`)이 '중고 노트북'·'듀얼 모니터 세트'처럼 **만든 곳을 말하지 않는
 * 방식**을 쓴다. 사양도 같은 규칙이라 프로세서를 "쿼드코어 1.60GHz"로 적는다 — 실존 브랜드도,
 * 그 브랜드를 흉내 낸 이름도 쓰지 않는다. 윈도우라는 이름만 예외인데, 이 게임의 화면 전체가
 * 이미 그 이름 위에 서 있다.
 *
 * ## 게임이 아는 사실 둘은 진짜다
 * 장치 이름은 **플레이어가 지은 이름**에서 오고, 설치 날짜는 **1일차**다. 나머지는 고정값이다 —
 * 두 줄이 진짜라서 이 창이 "남의 컴퓨터 스펙표"가 아니라 내 컴퓨터로 읽힌다.
 */

export interface SpecRow {
  label: string
  value: string
}

/** 장치 사양. 실제 윈도우 '정보' 화면의 첫 묶음과 같은 순서다. */
export function deviceSpecs(playerName: string): SpecRow[] {
  return [
    /* 이름을 안 지은 판은 없지만(잠금화면에서 받는다) 빈 문자열이 새어 들어오면
       "-PC"만 남으므로 그때는 기본 이름을 쓴다. */
    { label: '장치 이름', value: `${playerName || '사용자'}-PC` },
    { label: '프로세서', value: '쿼드코어 1.60GHz (4코어 8스레드)' },
    { label: '설치된 RAM', value: '8.00GB (7.85GB 사용 가능)' },
    { label: '저장소', value: '256GB SSD' },
    { label: '그래픽', value: '내장 그래픽' },
    { label: '시스템 종류', value: '64비트 운영 체제, x64 기반 프로세서' },
    {
      label: '펜 및 터치',
      value: '이 디스플레이에 사용할 수 있는 펜 또는 터치식 입력이 없습니다',
    },
  ]
}

/** 윈도우 사양. 설치 날짜만 게임 달력에서 온다. */
export function windowsSpecs(): SpecRow[] {
  return [
    { label: '에디션', value: '윈도우 11 Home' },
    { label: '버전', value: '23H2' },
    {
      label: '설치 날짜',
      /* 1일차 = 이 컴퓨터를 쓰기 시작한 날. `formatGameDate`를 안 쓰는 것은 실제 '정보'
         화면이 요일 없이 연·월·일만 적기 때문이다. */
      value: dateOf(1).toLocaleDateString('ko-KR'),
    },
    { label: 'OS 빌드', value: '22631.4169' },
  ]
}
