/**
 * 첫 실행 안내 투어의 문구와 순서. 화면 로직은 `components/desktop/Tour.tsx`에 있고
 * 여기 있는 것은 **무엇을 어떤 순서로 가리키는가**뿐이다.
 *
 * ## ⚠️ 가리키는 법은 `data-tour` 하나다
 * `.desktop-icon:nth-child(3)` 같은 순서 셀렉터를 쓰지 않는다 — 바탕화면 아이콘은
 * 드래그로 옮길 수 있고 조건부 항목(포토샵·갤러리·너아무튼온)이 있어 **순서가 정해지지
 * 않는다.** 대상 쪽에 `data-tour="<id>"`를 붙이고 투어는 그 속성만 본다.
 *
 * ## ⚠️ 항상 화면에 있는 것만 고른다
 * 조건부 아이콘을 가리키면 "안 보이는 것"을 가리키게 된다. 여기 실린 셋
 * (`browser`·`kakao`·`ledger`)은 `DESKTOP_ITEMS`에서 조건이 없는 항목이고,
 * `tour.test.ts`가 그 사실을 데이터에서 직접 확인한다.
 *
 * ## ⚠️ 누구에게나 참인 말만 적는다
 * 편성표 메시지와 같은 규칙이다 — "지원하신 곳"처럼 그 사람의 판에 달린 말을 적으면
 * 아무 일도 안 한 첫날에 거짓말이 된다.
 */
export interface TourStep {
  /** 단계 식별자. 진행 표시·키에만 쓴다. */
  id: string
  /** 가리킬 요소의 `data-tour` 값. */
  target: string
  title: string
  /** 한두 문장. 길어지면 카드가 화면을 덮는다. */
  text: string
}

