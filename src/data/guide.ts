/**
 * 첫 판 안내 — **이미 만들어 둔 것을 플레이어가 알게 하는 자리**(2026-08-14 신설).
 *
 * ## 왜 필요한가
 * 이 게임에는 시작 안내가 **한 줄도 없었다.** 잠금화면 → 이름 입력 → 바탕화면이고,
 * 1일차에 할 수 있는 활동이 **50개**인데 어디서부터 손대야 하는지 말해 주는 것이 없다.
 * 그래서 생활 등급·개인 기록·관계 단계·랭크 이벤트처럼 **만들어 둔 장치를 전부 스스로
 * 발견해야** 했다 — 만든 것이 늘수록 이 구멍이 커진다.
 *
 * ## ⚠️ 튜토리얼이 아니다
 * 화면을 가로막고 "여기를 누르세요"를 시키지 않는다(설계자의 기존 규칙 — 이 게임은
 * 손을 잡아끄는 대신 **세상이 말을 거는** 쪽이다). 여기 있는 것은 **메일 몇 통**이고,
 * 안 읽어도 게임은 그대로 돌아간다.
 *
 * ## ⚠️ 편성표(`MESSAGE_SCHEDULE`)에 넣지 않는 이유
 * 편성표는 `turn % length`로 **순환한다** — 넣으면 200일차에 "처음 오셨군요" 메일이
 * 다시 온다. 그래서 **한 번만 오는 것**으로 따로 둔다(랭크 이벤트와 같은 부류이고,
 * 기록도 `GameState.guides`에 남긴다).
 *
 * ## ⚠️ 플레이어가 한 일을 단정하지 않는다
 * 편성표와 같은 규칙이다. 여기 있는 말은 **누구에게나 참인 것**뿐이다 — "지원하신 곳"
 * 같은 문장은 아무 데도 안 넣은 사람에게 거짓말이 된다.
 */

export interface Guide {
  id: string
  /** 이 날이 되면 온다. 하루 2턴이므로 같은 날 둘을 두지 않는다(한 번에 몰리면 안 읽는다). */
  day: number
  /**
   * 보내는 이. ⚠️ **안내마다 다르다** — 전부 한 이름으로 오면 그 이름이 곧
   * "게임의 목소리"가 되어 가짜 OS라는 인상이 깨진다. 관리사무소는 사는 곳의 안내를,
   * 네이놈은 요약·기록을 보낸다.
   */
  from: string
  subject: string
  /**
   * 본문. ⚠️ **한 문단으로 쓴다** — 사서함 본문은 `white-space`가 기본값이라
   * 줄바꿈이 접힌다(다른 메일도 전부 한 문단이다). 문단을 나누려면 공용 CSS를 고쳐야 하고,
   * 그건 안내 넷 때문에 사서함 전체의 조판을 바꾸는 일이다.
   */
  text: string
}

