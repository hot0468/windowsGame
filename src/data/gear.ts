/**
 * 장비 고장 — **쓰면 닳는다.**
 *
 * ## 왜 만들었나
 * 이 게임에서 **나가는 돈이 전부 예측 가능했다**: 생활비는 물가표가 미리 알리고, 활동비는
 * 확인창이 미리 적고, 쇼핑은 내가 누른다. 그래서 **은행 대출을 굳이 안 써도 되고**
 * 두손마켓도 "정리용"이지 필요가 아니었다. 갑자기 필요한 목돈이 그 둘에 처음으로 쓸모를 준다.
 *
 * ## ⚠️ 무작위가 없다
 * 고장은 **그 장비를 몇 번 썼는가**의 함수다(`GameState.gear`). 주사위를 굴리면
 * "왜 하필 지금"에 답할 수 없고, 이 게임의 판정 규칙(정규직 합격·자격시험·공모전 심사)이
 * 전부 무작위를 뺀 것과 어긋난다. 몇 번 남았는지는 화면이 미리 말해 준다.
 *
 * ## ⚠️ 수리라는 새 통로를 만들지 않았다
 * 고장 나면 **인벤토리에서 빠지고, 다시 사면 그만이다** — 하이마루·쇼핑이 이미 그 자리를
 * 갖고 있다. 새 화면도 새 활동도 없다. 다만 **다시 받아도 스탯 효과는 없다**
 * (`systems/delivery.ts`의 `collect`) — 중고마켓 되사기와 정확히 같은 구멍이고 같은 자물쇠다.
 */

/** 닳는 장비 하나. */
export interface Gear {
  /** `data/items.ts`의 물건 id. */
  itemId: string
  /**
   * 이만큼 쓰면 고장 난다.
   *
   * ⚠️ **값비싼 장비가 더 오래 간다.** 액정 타블렛(115만)이 팬 타블렛(22만)보다 다섯 배
   * 비싼데 같이 부서지면 비싼 쪽을 살 이유가 등급 보너스 하나뿐이 된다.
   */
  uses: number
}

/**
 * 닳는 장비 목록.
 *
 * ⚠️ **회원권(헬스·미용실)은 넣지 않는다** — 그쪽은 물건이 아니라 **기간권**이고,
 * 이미 정기 결제라는 다른 축이 값을 받고 있다. 여기 넣으면 한 물건이 두 번 값을 받는다.
 * ⚠️ **자격증도 넣지 않는다** — 종이가 닳는다는 말이 되고, 다시 따려면 시험을 봐야 해서
 * "다시 사면 그만"이라는 이 시스템의 전제가 깨진다.
 */
export const GEARS: Gear[] = [
  { itemId: 'pen-tablet', uses: 12 },
  { itemId: 'lcd-tablet', uses: 30 },
  { itemId: 'streamkit', uses: 20 },
]

/** 남은 횟수가 이 이하면 화면이 미리 경고한다. */
export const GEAR_WARN_LEFT = 3

export function findGear(itemId: string): Gear | undefined {
  return GEARS.find((g) => g.itemId === itemId)
}
